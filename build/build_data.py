"""Analyse the 100 games and write web/games.js (for the app) and data/book.json (for the PDF)."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from features import analyse, opening_name
from commentary import narrate, short
from styles import EX

EVENT = {"St Petersburg9596": "St. Petersburg 1895–96", "Lodz1": "Lodz", "St Petersburg f": "St. Petersburg, final",
         "St Petersburg prel": "St. Petersburg, preliminary", "Buenos Aires Sicilian": "Sicilian theme tournament",
         "New York Rosenwald": "Rosenwald Memorial", "Teplitz-Schoenau": "Teplitz-Schönau", "San Sebastian": "San Sebastián",
         "Moscow-Prague": "Prague–Moscow match", "Hoogovens": "Hoogovens tournament", "Corus": "Corus tournament",
         "Italian Opera House": "A box at the opera", "London": "London tournament"}
TIEBREAK = {"Queen to h6", "Astana Tiebreak"}
PLAYOFF = {"Brussels Mayhem"}

games = json.load(open(os.path.join(ROOT, 'data/games.json')))
web, book = [], []
for g in games:
    ev = EVENT.get(g['event'], g['event'])
    if g['nick'] in TIEBREAK: ev = 'World Championship tiebreak'
    if g['nick'] in PLAYOFF: ev = 'Candidates playoff'
    if ev == g['site']: ev = g['site'] + ' tournament'
    rnd = g['round'].split('.')[0] if g['round'] else ''
    if 'World Championship' == ev and rnd: ev += f', game {rnd}'
    g['event'] = ev
    opening = opening_name(g['eco'], g['nick'])
    plies, _ = analyse(g)
    talk = narrate(g, plies, opening)
    author, exercise = EX[g['id']]
    def flags(d):
        return ''.join(c for c, on in (('x', d['cap']), ('c', d['check']), ('m', d['mate']), ('s', d['sac']), ('q', d['qoffer']),
                                        ('p', d['promo']), ('k', d['castle']), ('f', d['fork'])) if on)
    web.append(dict(id=g['id'], white=g['white'], black=g['black'], ws=short(g['white']), bs=short(g['black']), year=g['year'],
                    site=g['site'], event=ev, result=g['result'], nick=g['nick'], opening=opening, eco=g['eco'], author=author, exercise=exercise,
                    intro=dict(s=talk['s']['intro'], b=talk['b']['intro']), outro=dict(s=talk['s']['outro'], b=talk['b']['outro']),
                    plies=[[d['san'], d['uci'], flags(d), d['capv'], d['poss'], d['ex'], talk['s']['lines'][d['i']], talk['b']['lines'][d['i']]]
                           for d in plies]))
    book.append(dict(id=g['id'], white=g['white'], black=g['black'], ws=short(g['white']), bs=short(g['black']), year=g['year'], site=g['site'],
                     event=ev, result=g['result'], nick=g['nick'], opening=opening, author=author, exercise=exercise,
                     plies=[dict(san=d['san'], to=d['to'], frm=d['frm'], white=d['white'], cap=bool(d['cap']), check=d['check'], mate=d['mate'],
                                 piece=d['piece'], promo=d['promo'], bal=d['bal'], ex=d['ex'], sac=d['sac'] or d['qoffer']) for d in plies]))
with open(os.path.join(ROOT, 'web/games.js'), 'w') as f:
    f.write('// Generated by build/build_data.py — 100 historic games with play-by-play in two sports.\nwindow.GAMES = ')
    json.dump(web, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
json.dump(book, open(os.path.join(ROOT, 'data/book.json'), 'w'), ensure_ascii=False)
print('games.js', os.path.getsize(os.path.join(ROOT, 'web/games.js')) // 1024, 'KB')
if len(sys.argv) > 1:
    for gid in map(int, sys.argv[1:]):
        g = web[gid - 1]; b = book[gid - 1]
        print('\n=====', g['white'], '-', g['black'], g['year'], '|', g['event'], '|', g['opening'])
        for sp in 'sb':
            print('--', sp, '\n', g['intro'][sp])
            for p in g['plies']: print('  ', p[0].ljust(7), p[6 if sp == 's' else 7].replace('\n', '\n            '))
            print(' ', g['outro'][sp])
        print('--', b['author'], '\n', b['exercise'])
